import { z } from 'zod';

export const DataSourceSchema = z.enum(['LIVE', 'SIMULATED']);
export type DataSource = z.infer<typeof DataSourceSchema>;

export const ProviderSchema = z.enum(['MBTA', 'SIMULATOR']);
export type Provider = z.infer<typeof ProviderSchema>;

// ISO 8601 in UTC with a `Z` suffix only. Offsets such as `-05:00` are rejected:
// converting provider timestamps to UTC is the normalizer's job, not the contract's.
const utcTimestamp = z.iso.datetime();

const nonEmpty = z.string().min(1);

/**
 * A normalized vehicle position, independent of where it came from.
 */
export const VehicleObservationSchema = z
  .object({
    /** Stable across retries of the same event. How it is derived is up to the normalizer. */
    eventId: nonEmpty,
    /** `LIVE` pairs only with `MBTA`, `SIMULATED` only with `SIMULATOR`. */
    source: DataSourceSchema,
    provider: ProviderSchema,
    providerVehicleId: nonEmpty,
    routeId: nonEmpty.nullable(),
    tripId: nonEmpty.nullable(),
    lat: z.number().min(-90).max(90),
    lon: z.number().min(-180).max(180),
    /** Degrees, 0 to 360. */
    bearing: z.number().min(0).max(360).nullable(),
    /** Meters per second. */
    speedMps: z.number().min(0).nullable(),
    /**
     * When the vehicle was at this position. The provider's time when available
     * (`hasProviderTimestamp` is true), otherwise an estimate (false).
     */
    observedAt: utcTimestamp,
    /** When our application received the observation. Generated by us, never by the provider. */
    receivedAt: utcTimestamp,
    /** False when `observedAt` is estimated rather than reported by the provider. */
    hasProviderTimestamp: z.boolean(),
  })
  .refine(
    (o) =>
      (o.source === 'LIVE' && o.provider === 'MBTA') ||
      (o.source === 'SIMULATED' && o.provider === 'SIMULATOR'),
    {
      message:
        'source and provider must be LIVE + MBTA or SIMULATED + SIMULATOR',
      path: ['provider'],
    },
  );
export type VehicleObservation = z.infer<typeof VehicleObservationSchema>;
